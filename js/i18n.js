	function getText(el) {
		if (el.hasAttribute("data-i18n")) return el.getAttribute("data-i18n");
		var t = el.textContent.replace(/\s+/g, " ").trim();
		return t;
	}

	function apply(lang) {
		if (!D[lang]) lang = "en";
		var map = D[lang];
		document.documentElement.setAttribute("lang", lang);
		document.documentElement.setAttribute("dir", RTL[lang] ? "rtl" : "ltr");

		var nodes = document.querySelectorAll("[data-i18n]");
		for (var i = 0; i < nodes.length; i++) {
			var key = nodes[i].getAttribute("data-i18n");
			if (map && map[key] !== undefined) nodes[i].innerHTML = map[key];
		}

		var nodesPH = document.querySelectorAll("[data-i18n-ph]");
		for (var j = 0; j < nodesPH.length; j++) {
			var keyPH = nodesPH[j].getAttribute("data-i18n-ph");
			if (map && map[keyPH] !== undefined) nodesPH[j].setAttribute("placeholder", map[keyPH]);
		}

		try { localStorage.setItem("mergeit-lang", lang); } catch (e) {}
		var sel = document.getElementById("lang_select");
		if (sel && sel.value !== lang) sel.value = lang;
	}

	window.mergeItLang = { apply: apply };

	function init() {
		var sel = document.getElementById("lang_select");
		if (sel) {
			for (var i = 0; i < LANGS.length; i++) {
				var o = document.createElement("option");
				o.value = LANGS[i][0];
				o.textContent = LANGS[i][1] + " " + LANGS[i][2];
				sel.appendChild(o);
			}
			sel.addEventListener("change", function () { apply(sel.value); });
		}
		var saved = "en";
		try { saved = localStorage.getItem("mergeit-lang") || "en"; } catch (e) {}
		apply(saved);
		if (sel) sel.value = saved;
	}
	if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
